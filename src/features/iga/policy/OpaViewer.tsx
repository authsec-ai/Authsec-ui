/**
 * OpaViewer — read-only Rego source display with search, copy, and download.
 *
 * Shows the generated Rego from a policy compilation alongside source hashes,
 * compiler version, and entrypoint labels. Authored modules have an Edit button.
 */

import { useState, useCallback } from "react";
import { Copy, Download, Search, Code2 } from "lucide-react";
import { toast } from "react-hot-toast";

import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Panel, Facts, Fact } from "@/features/iga/shared/components/Panel";
import { StatusBadge } from "@/components/console/status";

import type { AuthoredModule, PolicyRevision } from "./policyApi";

// ── Props ────────────────────────────────────────────────────────────────────

interface OpaViewerProps {
  revision: PolicyRevision | null;
  generatedRego?: string;
  authoredModules?: AuthoredModule[];
  compilerVersion?: string;
  sourceHash?: string;
  regoHash?: string;
  wasmDigest?: string;
  onEditModule?: (moduleName: string) => void;
}

// ── Component ────────────────────────────────────────────────────────────────

export function OpaViewer({
  revision,
  generatedRego,
  authoredModules = [],
  compilerVersion,
  sourceHash,
  regoHash,
  wasmDigest,
  onEditModule,
}: OpaViewerProps) {
  const [searchTerm, setSearchTerm] = useState("");
  const [showSearch, setShowSearch] = useState(false);

  const regoSource = generatedRego || revision?.generated_rego || "";

  const handleCopy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(regoSource);
      toast.success("Rego copied to clipboard");
    } catch {
      toast.error("Failed to copy");
    }
  }, [regoSource]);

  const handleDownload = useCallback(() => {
    const blob = new Blob([regoSource], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `policy-${revision?.revision ?? "unknown"}.rego`;
    a.click();
    URL.revokeObjectURL(url);
  }, [regoSource, revision]);

  // Highlight search matches in content
  const highlightedLines = regoSource.split("\n").map((line, idx) => {
    const lineNum = idx + 1;
    const isMatch =
      searchTerm && line.toLowerCase().includes(searchTerm.toLowerCase());
    return { line, lineNum, isMatch };
  });

  if (!regoSource && authoredModules.length === 0) {
    return (
      <Panel title="OPA / Rego Source">
        <p className="text-sm text-(--color-text-muted)">
          No generated Rego or authored modules available for this revision.
        </p>
      </Panel>
    );
  }

  return (
    <div className="space-y-4">
      {/* Metadata panel */}
      <Panel title="Compilation Info">
        <Facts>
          {compilerVersion && (
            <Fact label="Compiler Version" mono>{compilerVersion}</Fact>
          )}
          {revision?.compiler_format && (
            <Fact label="Format">{revision.compiler_format}</Fact>
          )}
          {sourceHash && (
            <Fact label="Source Hash" mono>{sourceHash.slice(0, 16)}...</Fact>
          )}
          {regoHash && (
            <Fact label="Rego Hash" mono>{regoHash.slice(0, 16)}...</Fact>
          )}
          {wasmDigest && (
            <Fact label="Wasm Digest" mono>{wasmDigest.slice(0, 16)}...</Fact>
          )}
          {revision?.capability_digest && (
            <Fact label="Capability Digest" mono>
              {revision.capability_digest.slice(0, 16)}...
            </Fact>
          )}
        </Facts>
      </Panel>

      {/* Generated Rego */}
      {regoSource && (
        <Panel
          title="Generated Rego"
          description="Read-only — generated by the policy compiler"
        >
          <div className="flex items-center gap-2 mb-3">
            <Button
              variant="outline"
              size="sm"
              className="gap-1.5"
              onClick={() => setShowSearch(!showSearch)}
            >
              <Search className="size-3.5" />
              Search
            </Button>
            <Button
              variant="outline"
              size="sm"
              className="gap-1.5"
              onClick={handleCopy}
            >
              <Copy className="size-3.5" />
              Copy
            </Button>
            <Button
              variant="outline"
              size="sm"
              className="gap-1.5"
              onClick={handleDownload}
            >
              <Download className="size-3.5" />
              Download
            </Button>
            <StatusBadge tone="neutral">read-only</StatusBadge>
          </div>

          {showSearch && (
            <Input
              placeholder="Search in Rego..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="mb-3 max-w-sm text-sm"
              autoFocus
            />
          )}

          <div className="max-h-[600px] overflow-auto rounded-md border border-(--color-border-subtle) bg-(--color-surface-subtle)">
            <pre className="text-xs leading-relaxed">
              {highlightedLines.map(({ line, lineNum, isMatch }) => (
                <div
                  key={lineNum}
                  className={
                    "flex hover:bg-(--color-surface-subtle)/80 " +
                    (isMatch
                      ? "bg-yellow-100/50 dark:bg-yellow-900/20"
                      : "")
                  }
                >
                  <span className="w-12 shrink-0 select-none px-2 py-px text-right text-(--color-text-muted) opacity-50">
                    {lineNum}
                  </span>
                  <code className="flex-1 px-2 py-px whitespace-pre">
                    {line}
                  </code>
                </div>
              ))}
            </pre>
          </div>
        </Panel>
      )}

      {/* Authored modules */}
      {authoredModules.length > 0 && (
        <Panel
          title="Authored Modules"
          count={`${authoredModules.length} module${authoredModules.length !== 1 ? "s" : ""}`}
        >
          <div className="space-y-3">
            {authoredModules.map((mod) => (
              <div key={mod.name} className="rounded-md border border-(--color-border-subtle) p-3">
                <div className="flex items-center justify-between mb-2">
                  <div className="flex items-center gap-2">
                    <Code2 className="size-4 text-(--color-text-muted)" />
                    <span className="text-sm font-medium">{mod.name}</span>
                    <StatusBadge tone="info">{mod.language}</StatusBadge>
                  </div>
                  {onEditModule && (
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => onEditModule(mod.name)}
                    >
                      Edit
                    </Button>
                  )}
                </div>
                {mod.hash && (
                  <p className="text-xs font-mono text-(--color-text-muted) mb-2">
                    SHA-256: {mod.hash.slice(0, 16)}...
                  </p>
                )}
                <pre className="max-h-64 overflow-auto rounded-md bg-(--color-surface-subtle) p-2 text-xs leading-relaxed">
                  {mod.source}
                </pre>
              </div>
            ))}
          </div>
        </Panel>
      )}
    </div>
  );
}
